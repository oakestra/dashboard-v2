/**
 * Regenerates `src/generated/schema.d.ts` from the system-manager OpenAPI document.
 *
 *   pnpm gen:api                       refresh specs/ from http://localhost:10000/docs/openapi.json
 *   pnpm gen:api <url>                 refresh specs/ from another system-manager
 *   pnpm gen:api --offline             only regenerate types from the committed snapshot
 *
 * The snapshot in specs/ is committed so builds never need a running backend, and so a spec change
 * shows up as a reviewable diff.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';

const DEFAULT_URL = 'http://localhost:10000/docs/openapi.json';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = resolve(root, 'specs/system-manager.json');
const outPath = resolve(root, 'src/generated/schema.d.ts');

const args = process.argv.slice(2);
const offline = args.includes('--offline');
const url =
  args.find((arg) => !arg.startsWith('--')) ?? process.env.OAKESTRA_OPENAPI_URL ?? DEFAULT_URL;

interface OpenApiDocument {
  paths: Record<string, unknown>;
  [key: string]: unknown;
}

async function fetchSpec(source: string): Promise<OpenApiDocument> {
  let response: Response;
  try {
    response = await fetch(source);
  } catch (error) {
    throw new Error(
      `Could not reach ${source} (${String(error)}). Start a system-manager or run with --offline.`,
    );
  }
  if (!response.ok) throw new Error(`${source} returned HTTP ${response.status}`);
  return (await response.json()) as OpenApiDocument;
}

/**
 * The backend mounts everything below `/api`, and the dashboard config's `apiUrl` already ends in
 * `/api` (that is what API_ADDRESS has always mapped to). Dropping the prefix here lets the client
 * use `apiUrl` as its base URL unchanged.
 */
function stripApiPrefix(spec: OpenApiDocument): OpenApiDocument {
  const paths = Object.fromEntries(
    Object.entries(spec.paths).map(([path, item]) => [path.replace(/^\/api(?=\/)/, ''), item]),
  );
  return { ...spec, paths };
}

let spec: OpenApiDocument;
if (offline) {
  spec = JSON.parse(await readFile(specPath, 'utf8')) as OpenApiDocument;
} else {
  spec = await fetchSpec(url);
  await writeFile(specPath, `${JSON.stringify(spec, null, 2)}\n`);
  console.log(`gen:api: saved ${url} to ${specPath}`);
}

const ast = await openapiTS(stripApiPrefix(spec) as unknown as OpenAPI3, {
  // The spec has almost no response schemas; `unknown` keeps callers honest about parsing.
  emptyObjectsUnknown: true,
});
const header =
  '// Generated by packages/api/scripts/gen-api.ts from specs/system-manager.json. Do not edit.\n' +
  "// Paths are relative to the configured apiUrl, i.e. without the backend's /api prefix.\n\n";
await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, header + astToString(ast));
console.log(`gen:api: wrote ${outPath}`);
